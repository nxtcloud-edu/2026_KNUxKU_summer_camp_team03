def lookup(text: str) -> tuple[str, dict] | None:
    """질문에서 사전 용어를 찾는다. 가장 구체적인(별칭이 긴) 매칭 우선."""
    q = text.lower()
    best: tuple[str, dict, int] | None = None
    for term, entry in GLOSSARY.items():
        for alias in entry["aliases"]:
            if alias.lower() in q and (best is None or len(alias) > best[2]):
                best = (term, entry, len(alias))
    return (best[0], best[1]) if best else None


def explain(term: str, entry: dict, level: str) -> str:
    """수준에 맞는 해설을 고른다. 모르는 수준이면 beginner로 폴백."""
    return entry["levels"].get(level, entry["levels"]["beginner"])
